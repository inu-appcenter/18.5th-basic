// 3. 복합 대입 연산자
// 산술연산자 + 대입연산자 라고 보면된다.
let num7 = 10;
num7= num7 + 20; //변수를 두번 적어야 해서 번거롭다.
num7 +=20; //따라서 복합 대입 연산자를 사용한다.
