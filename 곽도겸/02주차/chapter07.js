// 4. 증감 연산자
let num8 = 10;
num8++; //이 라인이 지나야 증가 된다.
++num8;//현재 라인에서 증가 시키고 싶으면 변수명 앞에 ++를 붙여주면 된다 이같은 연산자를 전위 연산이라고 한다. 반대로 뒤에 붙이면 후위연산이다.

// 5. 논리 연산자
