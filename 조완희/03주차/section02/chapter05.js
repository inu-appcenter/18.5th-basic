// ---

// ### **주제: 객체 타입 주의사항 1. 의도치 않게 값이 수정될 수 있다.**

// #### **1. 코드 분석**

// ```javascript
// let o1 = { name: "이정환" };
// let o2 = { ...o1 };

// ```

// * **`let o1 = { name: "이정환" };`**

// * `o1` 변수에 `{ name: "이정환" }` 객체를 할당합니다.

// * **`let o2 = { ...o1 };`**

// * 전개 연산자(`...`, Spread Operator)를 사용하여 `o1` 객체의 속성을 복사하여 **새로운 객체** `o2`를 생성합니다.

// ---

// #### **2. 메모리(Memory) 구조 및 동작 원리**

// * **`o1` 변수**

// * 메모리상에서 참조값(`0x0000C`)을 가리킵니다.

// * 해당 참조값에는 실제 객체 데이터인 `{ name: "이정환" }`이 저장되어 있습니다.

// * **`o2` 변수**

// * 전개 연산자(`...`)를 사용해 새로운 객체를 만들었기 때문에, `o1`과는 서로 다른 참조값(`0x0000D`)을 갖게 됩니다.

// * 참조값 `0x0000D` 주소에 독립적인 `{ name: "이정환" }` 객체가 새로 생성되어 저장됩니다.

// ---

// #### **3. 핵심 요약**

// * 단순 할당(`let o2 = o1`)을 할 경우에는 두 변수가 같은 참조값을 공유하므로 한쪽을 수정하면 다른 쪽도 의도치 않게 변경될 수 있습니다.

// * 하지만 이미지와 같이 전개 연산자(`{ ...o1 }`)를 사용한 얕은 복사(Shallow Copy)를 진행하면, 새로운 참조값(`0x0000D`)이 생성되어 메모리 영역이 분리됩니다.

// 제공해주신 이미지 내용을 바탕으로 정리한 내용은 다음과 같습니다.

// ---

// ### **얕은 복사 vs 깊은 복사**

// | 구분 | **얕은 복사** | **깊은 복사** |
// | --- | --- | --- |
// | **코드** | `let o1 = { name: "이정환" };`<br>

// <br>`let o2 = o1;`<br> | `let o1 = { name: "이정환" };`<br>

// <br>`let o2 = { ...o1 };`<br> |
// | **동작 방식** | 객체의 **참조값(메모리 주소)**을 복사함

//  | **새로운 객체**를 생성하면서 프로퍼티만 따로 복사함

//  |
// | **특징 및 안정성** | 원본 객체가 수정될 수 있어 **위험함**<br> | 원본 객체가 수정될 일이 없어 **안전함**<br> |

// ---

// #### **1. 얕은 복사 (Shallow Copy)**

// * **원리**: `o2` 변수에 `o1`을 그대로 할당하면 실제 객체가 아닌 **참조값(메모리 주소)만 복사**됩니다.

// * **문제점**: `o1`과 `o2`가 같은 메모리 주소를 가리키므로, `o2`의 값을 변경하면 `o1`의 값도 함께 바뀌는 부작용(Side Effect)이 발생할 수 있어 위험합니다.

// #### **2. 깊은 복사 (Deep Copy)**

// * **원리**: 전개 연산자(`...`) 등을 사용하면 **새로운 객체를 생성**하면서 내부 프로퍼티 값만 따로 따와서 복사합니다.

// * **장점**: `o1`과 `o2`가 서로 다른 메모리 주소를 가리키게 되므로, 어느 한쪽을 수정해도 원본 객체에 영향을 주지 않아 안전합니다.
